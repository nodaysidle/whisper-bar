import Foundation

// MARK: - ReplacementRule

/// One deterministic text replacement rule mapping spoken or misrecognized phrases
/// to the user's exact technical identifier or casing.
struct ReplacementRule: Equatable, Sendable, Codable {
    let id: String
    let original: String
    let `with`: String

    init(id: String = UUID().uuidString, original: String, with: String) {
        self.id = id
        self.original = original
        self.with = with
    }
}

// MARK: - File Format Serialization

private struct VocabularyDictionaryFile: Codable {
    let schemaVersion: Int?
    let source: String?
    let vocabulary: [String]?
    let replacements: [ReplacementRule]?
}

// MARK: - VocabularyReplacementEngine

/// OWN-CUSTOM-WRITING-MODES-AND-VOCABULARY / OWN-PASTE-COORDINATOR.
///
/// Seeded from SuperWhisper dictionary (290+ vocabulary terms, 260+ replacement rules).
/// Applies case-insensitive regex word boundary replacements (`\b...\b`) ensuring that
/// spoken phrases (e.g. "no days idle", "post grass", "clod code") are accurately
/// transformed into exact project identifiers (e.g. "nodaysidle", "PostgreSQL", "Claude Code").
struct VocabularyReplacementEngine: Sendable {

    let rules: [ReplacementRule]
    let vocabulary: [String]
    private let compiledRules: [CompiledRule]

    private struct CompiledRule: @unchecked Sendable {
        let original: String
        let regex: NSRegularExpression
        let template: String
    }

    static let `default`: VocabularyReplacementEngine = VocabularyReplacementEngine()

    init(rules: [ReplacementRule] = Self.seededRules, vocabulary: [String] = Self.seededVocabulary) {
        // Sort rules by original phrase length descending so longer compound phrases match before shorter fragments
        let sortedRules = rules.sorted { $0.original.count > $1.original.count }
        self.rules = sortedRules
        self.vocabulary = vocabulary

        var compiled: [CompiledRule] = []
        for rule in sortedRules {
            let trimmed = rule.original.trimmingCharacters(in: .whitespacesAndNewlines)
            guard !trimmed.isEmpty else { continue }
            let pattern = "\\b" + NSRegularExpression.escapedPattern(for: trimmed) + "\\b"
            if let regex = try? NSRegularExpression(pattern: pattern, options: [.caseInsensitive]) {
                let template = NSRegularExpression.escapedTemplate(for: rule.with)
                compiled.append(CompiledRule(original: trimmed, regex: regex, template: template))
            }
        }
        self.compiledRules = compiled
    }

    /// Loads custom vocabulary rules from a JSON file on disk (matching SuperWhisper schema).
    init(contentsOf fileURL: URL) throws {
        let data = try Data(contentsOf: fileURL)
        let decoded = try JSONDecoder().decode(VocabularyDictionaryFile.self, from: data)
        self.init(
            rules: decoded.replacements ?? Self.seededRules,
            vocabulary: decoded.vocabulary ?? Self.seededVocabulary
        )
    }

    /// Creates an engine combining seeded vocabulary with custom terms from DataStore.
    static func from(dataStore: DataStore) async -> VocabularyReplacementEngine {
        let customTerms = (try? await dataStore.vocabularyTerms())?.map(\.term) ?? []
        let combinedVocab = Self.seededVocabulary + customTerms
        return VocabularyReplacementEngine(rules: Self.seededRules, vocabulary: combinedVocab)
    }

    /// Applies word-boundary case-insensitive replacements in the provided text.
    func replace(in text: String) -> String {
        guard !text.isEmpty else { return text }
        var result = text
        for item in compiledRules {
            guard result.localizedCaseInsensitiveContains(item.original) else {
                continue
            }
            let nsRange = NSRange(result.startIndex..<result.endIndex, in: result)
            result = item.regex.stringByReplacingMatches(
                in: result,
                options: [],
                range: nsRange,
                withTemplate: item.template
            )
        }
        return result
    }

